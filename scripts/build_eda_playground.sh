#!/usr/bin/env bash
# Concatenate the RTL and UVM testbench into the two files EDA Playground expects.
#   eda_playground/design.sv     -> paste into the right-hand "design.sv" pane
#   eda_playground/testbench.sv  -> paste into the left-hand "testbench.sv" pane
set -euo pipefail
cd "$(dirname "$0")/.."
out=eda_playground
mkdir -p "$out"

{
  echo "// design.sv - generated by scripts/build_eda_playground.sh. Do not edit; edit rtl/ instead."
  echo '`timescale 1ns/1ps'
  for f in rtl/pe.sv rtl/systolic_array.sv rtl/accel_core.sv rtl/axil_slave.sv rtl/accel_top.sv; do
    echo; echo "// ==== $f ===="; cat "$f"
  done
} > "$out/design.sv"

{
  echo "// testbench.sv - generated by scripts/build_eda_playground.sh. Do not edit; edit tb/uvm/ instead."
  echo "// Select: SystemVerilog/Verilog, UVM 1.2, and Synopsys VCS / Cadence Xcelium / Aldec Riviera-PRO."
  echo "// Run options: +UVM_TESTNAME=full_regression_test +NUM_ITERS=60"
  echo '`timescale 1ns/1ps'
  echo '`include "uvm_macros.svh"'
  for f in tb/uvm/axil_if.sv tb/uvm/accel_tb_pkg.sv tb/uvm/accel_sva.sv tb/uvm/tb_top.sv; do
    echo; echo "// ==== $f ===="; cat "$f"
  done
} > "$out/testbench.sv"

echo "Wrote $out/design.sv and $out/testbench.sv"
